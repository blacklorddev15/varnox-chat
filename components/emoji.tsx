export function EmojiPanel({ onPick }: { onPick: (emoji: string) => void }) {
  const [tab, setTab] = useState(CATEGORIES[0].id);
  const active = CATEGORIES.find((c) => c.id === tab) ?? CATEGORIES[0];

  return (
    <div className="emoji-panel">
      <div className="emoji-tabs">
        {CATEGORIES.map((c) => (
          <button
            key={c.id}
            type="button"
            className={`emoji-tab${c.id === tab ? ' on' : ''}`}
            onClick={() => setTab(c.id)}
          >
            {c.label}
          </button>
        ))}
      </div>
      <div className="emoji-grid">
        {active.items.map((e) => (
          <button key={e} type="button" onClick={() => onPick(e)} aria-label={e}>
            {e}
          </button>
        ))}
      </div>
    </div>
  );
}
